-- 3. Por cada fila: obtener/crear producto, variante (color), talle (stock)
DO $$
DECLARE
  c_id UUID;
  p_id UUID;
  v_id UUID;
  r RECORD;
BEGIN
  FOR r IN SELECT * FROM _catalog
  LOOP
    SELECT id INTO c_id FROM categories WHERE slug = r.cat_slug LIMIT 1;
    IF c_id IS NULL THEN RAISE NOTICE 'Categoría no encontrada: %', r.cat_slug; CONTINUE; END IF;
    SELECT id INTO p_id FROM products WHERE name = r.pname AND category_id = c_id LIMIT 1;
    IF p_id IS NULL THEN
      INSERT INTO products (name, category_id, price, stock) VALUES (r.pname, c_id, r.price, 0) RETURNING id INTO p_id;
    END IF;
    INSERT INTO product_variants (product_id, color, stock) VALUES (p_id, r.color, 0)
      ON CONFLICT (product_id, color) DO NOTHING;
